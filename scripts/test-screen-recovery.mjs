import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';
import vm from 'node:vm';
const source = await readFile(new URL('../src/App.tsx', import.meta.url), 'utf8');
const start = source.indexOf('function lazyWithRetry');
const end = source.indexOf('\nconst TrinityApp', start);
const code = stripTypeScriptTypes(source.slice(start, end));
const context = vm.createContext({ React: { lazy: loader => loader }, setTimeout: callback => { callback(); return 0; } });
const lazyWithRetry = vm.runInContext(code + '; lazyWithRetry', context);
let calls = 0;
const component = { default: () => null };
assert.equal(await lazyWithRetry(async () => { calls++; if(calls < 3) throw new Error('Failed to fetch dynamically imported module'); return component; })(), component);
assert.equal(calls, 3);
calls = 0;
await assert.rejects(lazyWithRetry(async () => { calls++; throw new Error('Render bug'); })(), /Render bug/);
assert.equal(calls, 1);
calls = 0;
await assert.rejects(lazyWithRetry(async () => { calls++; throw new Error('Loading chunk failed'); })(), /Loading chunk/);
assert.equal(calls, 3);
assert.match(source, /<ErrorBoundary key={cleanLoc}>/);
const boundary = await readFile(new URL('../src/components/ErrorBoundary.tsx', import.meta.url), 'utf8');
assert.doesNotMatch(boundary, /error?.stack/);
console.log('Passed: transient module recovery, bounded retries, render errors fail immediately, per-route isolation and no raw error stacks.');
