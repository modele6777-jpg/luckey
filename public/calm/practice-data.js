/**
 * 도서 쪽수 기반 가장 적합한 실천 연습 매칭
 */
window.BOOK_PAGE_INDEX = function(pageNum, book) {
  pageNum = parseInt(pageNum, 10) || 18;
  if (!window.PRACTICE_EXERCISES || window.PRACTICE_EXERCISES.length === 0) {
    return {
      chapter: "1장 · 머릿속 혼돈과 거리 두기",
      title: "연습 1. 걱정 그리기 (18쪽)",
      desc: "오감 스케치와 인지적 탈융합",
      exerciseIdx: 1
    };
  }

  let candidates = window.PRACTICE_EXERCISES;
  if (book === '예민' || book === 'hsp' || pageNum > 160) {
    candidates = window.PRACTICE_EXERCISES.filter(e => e.globalIndex > 40);
  } else if (book === '불안' || book === 'calm') {
    candidates = window.PRACTICE_EXERCISES.filter(e => e.globalIndex <= 40);
  }
  if (!candidates.length) candidates = window.PRACTICE_EXERCISES;

  let bestEx = candidates[0];
  let minDiff = 9999;
  candidates.forEach(ex => {
    const diff = Math.abs(ex.page - pageNum);
    if (diff < minDiff) {
      minDiff = diff;
      bestEx = ex;
    }
  });

  return {
    chapter: `${bestEx.chapter}장 · ${bestEx.chapterTitle}`,
    title: `연습 ${bestEx.globalIndex}. ${bestEx.title} (${bestEx.page}쪽)`,
    desc: `${bestEx.subtitle || ''} - ${bestEx.purpose || bestEx.description || ''}`,
    exerciseIdx: bestEx.globalIndex
  };
};

// 하위 호환성 및 undefined 방지 보장: description과 purpose 상호 매핑
if (window.PRACTICE_EXERCISES) {
  window.PRACTICE_EXERCISES.forEach(ex => {
    if (!ex.description && ex.purpose) ex.description = ex.purpose;
    if (!ex.purpose && ex.description) ex.purpose = ex.description;
  });
}
