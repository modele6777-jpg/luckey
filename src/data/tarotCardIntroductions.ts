export function getTarotCardIntroduction(card: {
  id?: string;
  nameKo?: string;
  keywords?: readonly string[];
} | null | undefined): string {
  if (!card) return '';
  const introduction = card.id ? TAROT_CARD_INTRODUCTIONS[card.id] : undefined;
  if (introduction) return introduction;

  const keywords = card.keywords?.filter(Boolean).slice(0, 3).join('·');
  if (keywords) return `이 카드는 ${keywords}의 흐름을 상징합니다.`;
  return `${card.nameKo || '이 카드'}의 기본 상징을 살펴보는 카드입니다.`;
}
