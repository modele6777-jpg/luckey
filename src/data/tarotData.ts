/** 약 40% 확률로 역방향 (drawCards와 동일 비율) */
export function rollTarotReversed(): boolean {
  return Math.random() > 0.6;
}

export function formatTarotOrientation(card: TarotCard): string {
  return card.reversed ? '역방향' : '정방향';
}

