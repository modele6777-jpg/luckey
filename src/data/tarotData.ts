/**
 * 카드가 역방향이면 정방향 키워드 대신 역방향 전용 키워드를 반환하고, 정방향이면 기본 키워드를 반환합니다.
 */
export function getEffectiveTarotKeywords(
  card: { id?: string; nameKo?: string; type?: string; keywords?: string[]; reversed?: boolean } | null | undefined
): string[] {
  if (!card) return [];
  if (card.reversed) {
    return getTarotReversedData(card).keywords;
  }
  return Array.isArray(card.keywords) ? card.keywords : [];
}

/**
 * 역방향 카드에 대한 핵심 주의점 1가지(caution)를 반환합니다.
 */
export function getTarotCardCaution(
  card: { id?: string; nameKo?: string; type?: string; keywords?: string[]; reversed?: boolean } | null | undefined
): string {
  if (!card) return '';
  return getTarotReversedData(card).caution;
}

