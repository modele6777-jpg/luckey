/** 중심 고민에서 상담 주제를 읽는다. */
export function detectMasterConcernTopic(concern: string): MasterConcernTopic {
  const text = (concern || '').replace(/\s+/g, ' ');
  if (!text) return 'general';
  if (/(연애|사랑|남친|여친|애인|그\s*사람|썸|재회|이별|헤어|결혼|짝사랑|궁합|인연|연락)/.test(text)) return 'love';
  if (/(이직|퇴사|회사|직장|취업|진로|승진|사업|일이|일을|일\s|상사|커리어|시험|합격)/.test(text)) return 'career';
  if (/(돈|재물|빚|대출|투자|주식|수입|월급|재테크|경제)/.test(text)) return 'money';
  if (/(불안|우울|외로|지쳐|힘들|마음|상처|무서|두려|자존감|번아웃)/.test(text)) return 'mind';
  return 'general';
}

function shuffle<T>(items: readonly T[]): T[] {
  const copy = [...items];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

/** 깊이(와 고민 주제)에 맞는 추천 질문 6개. 주제 질문을 먼저, 나머지는 같은 깊이의 일반 질문으로 채운다. */
export function getMasterDepthPrompts(depth: LucyMasterDepth, topic: MasterConcernTopic = 'general', count = 6): string[] {
  const topical = topic === 'general' ? [] : shuffle(TOPIC[topic][depth]);
  const general = shuffle(GENERAL[depth]);
  return [...new Set([...topical, ...general])].slice(0, count);
}
