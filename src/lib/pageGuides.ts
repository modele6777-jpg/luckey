const PROLOGUE_ALIASES = ['/prologue', '/universe', '/ecpr', '/todo', '/mission', '/synergy', '/aegis'];

export function resolvePageGuide(path: string, options: { master?: boolean } = {}): PageGuide {
  const clean = (path.split(/[?#]/)[0] || '/').toLowerCase();
  if (['/', '/chat', '/lucy', '/chat/pro'].includes(clean)) return options.master ? GUIDES.master : GUIDES.lucy;
  if (['/key', '/calm', '/orb', '/gateway', '/crystal', '/pharmacy'].some(p => clean === p || clean.startsWith(`${p}/`))) return GUIDES.key;
  if (DAPP_GUIDES[clean]) return DAPP_GUIDES[clean];
  if (PROLOGUE_ALIASES.some(p => clean === p || clean.startsWith(`${p}/`))) return DAPP_GUIDES['/prologue'];
  for (const id of ['orange', 'trinity', 'heal', 'bluebird', 'muse', 'library'] as const) {
    if (clean === `/${id}` || clean.startsWith(`/${id}/`)) return DAPP_GUIDES[`/${id}`] ?? GUIDES[id];
  }
  if (['/epilogue', '/profile', '/chronicle'].includes(clean)) return DAPP_GUIDES[clean] ?? GUIDES.epilogue;
  return GUIDES.default;
}

export function getPageGuide(id: string): PageGuide {
  return GUIDES[id] ?? GUIDES.default;
}

/** dApp(채널 안 화면) 가이드. 없으면 채널 가이드. */
export function resolveDappGuide(pageKey: string): PageGuide {
  const clean = (pageKey || '/').startsWith('/') ? pageKey : `/${pageKey}`;
  return DAPP_GUIDES[clean] ?? resolvePageGuide(clean.split('?')[0]);
}

/** Key 안의 현재 탭 가이드. 없으면 Key 전체 가이드. */
export function resolveKeyTabGuide(tab?: string | null): PageGuide {
  return (tab && KEY_TAB_GUIDES[tab]) || GUIDES.key;
}

export type PageGuideSection = 'guide' | 'tips' | 'uses';

/** Text read aloud by the guide's listen button (the section being viewed). */
export function pageGuideSpeech(guide: PageGuide, section: PageGuideSection = 'guide'): string {
  if (section === 'uses') {
    return [`${guide.title} 추천 활용.`, ...guide.uses.map((use, index) => `${index + 1}. ${use.when}, ${use.how}`)].join('\n');
  }
  if (section === 'tips') {
    return [`${guide.title} 활용 팁.`, ...guide.tips.map((tip, index) => `${index + 1}. ${tip.text}`)].join('\n');
  }
  return [`${guide.title} 사용 가이드.`, guide.intro, ...guide.steps.map((step, index) => `${index + 1}단계. ${step}`)].join('\n');
}

