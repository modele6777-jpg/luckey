export const ICHING_CARDS: readonly IchingCard[] = ROWS.map(([name, hanja, judgment, core, use, caution], index) => ({
  number: index + 1, name, hanja, judgment, core, use, caution,
}));

const BY_NAME = new Map(ICHING_CARDS.map(card => [card.name, card]));

/** '뇌지예 (진 ☳ 위, 곤 ☷ 아래)' 같은 표기에서도 괘 이름으로 카드를 찾는다. */
export function findIchingCard(nameOrLabel: string | undefined | null): IchingCard | null {
  if (!nameOrLabel) return null;
  const name = String(nameOrLabel).trim().split(/[\s(]/)[0];
  return BY_NAME.get(name) ?? null;
}

export function formatIchingCard(card: IchingCard, role: string): string {
  return `${role} ${card.number}. ${card.name}(${card.hanja}) — 괘사 「${card.judgment}」 · 뜻: ${card.core} · 쓰임: ${card.use} · 주의: ${card.caution}`;
}
