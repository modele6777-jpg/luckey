export function formatSimpleCard(label: string, c: SimpleCard): string {
  return `${label} — 뜻: ${c.core} · 쓰임: ${c.use} · 주의: ${c.caution}`;
}

export const findCard = (cards: readonly SimpleCard[], key: string | undefined | null) => (key ? cards.find(c => c.key === key) ?? null : null);

